"""The served bundles carry no source comments (#1224)."""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))

import build_bundle  # noqa: E402
import build_css  # noqa: E402
from strip_comments import js_tokens, strip_css, strip_js  # noqa: E402

WWW = REPO / "custom_components" / "quizify" / "www"
JS_SOURCES = sorted((WWW / "js").glob("*.js"))
JS_SOURCES = [p for p in JS_SOURCES if not p.name.endswith(".bundle.js")]
CSS_SOURCES = sorted((WWW / "css" / "src").glob("*.css"))


def test_sources_found():
    assert len(JS_SOURCES) > 15 and len(CSS_SOURCES) >= 10


@pytest.mark.parametrize("path", JS_SOURCES, ids=lambda p: p.name)
def test_js_strip_idempotent_and_keeps_tokens(path):
    src = path.read_text("utf-8")
    out = strip_js(src)
    assert strip_js(out) == out
    assert js_tokens(out) == js_tokens(src)
    assert len(out) <= len(src)
    assert "\n\n\n" not in out or "\n\n\n" in src


@pytest.mark.parametrize("path", CSS_SOURCES, ids=lambda p: p.name)
def test_css_strip_idempotent(path):
    out = strip_css(path.read_text("utf-8"))
    assert strip_css(out) == out
    assert "/*" not in re.sub(r"""(["'])(?:\\.|(?!\1).)*\1""", "", out)


@pytest.mark.skipif(shutil.which("node") is None, reason="node not installed")
def test_stripped_js_still_parses(tmp_path):
    for path in JS_SOURCES:
        out = tmp_path / path.name
        out.write_text(strip_js(path.read_text("utf-8")), "utf-8")
        res = subprocess.run(
            ["node", "--check", str(out)], capture_output=True, text=True
        )
        assert res.returncode == 0, f"{path.name}: {res.stderr}"


def test_strip_js_edge_cases():
    src = (
        "// gone\n"
        "var a = 'x // keep', b = \"/* keep */\";\n"
        "var re = /[/*]x\\//g; // trailing\n"
        "var d = a / 2 / 3; /* inline */ var q = 1;\n"
        "var t = `x ${ y /* in expr */ + `n${1}` } // text`;\n"
        "/*! legal */\n"
        "/* block\n   comment */\n"
        "return /x/.test(a);\n"
    )
    out = strip_js(src)
    assert out == (
        "var a = 'x // keep', b = \"/* keep */\";\n"
        "var re = /[/*]x\\//g;\n"
        "var d = a / 2 / 3; var q = 1;\n"
        "var t = `x ${ y + `n${1}` } // text`;\n"
        "/*! legal */\n"
        "return /x/.test(a);\n"
    )


def test_strip_css_edge_cases():
    src = (
        "/* a */\n.a{b:url(x//y) /* c */ c}\n\n/* d */\n\n"
        ".e{content:'/* x */'}\n"
    )
    assert strip_css(src) == ".a{b:url(x//y) c}\n\n.e{content:'/* x */'}\n"


def test_built_outputs_have_no_comments_but_the_header():
    for name in ("styles.css", "tv.css"):
        text = (WWW / "css" / name).read_text("utf-8")
        assert text.startswith("/* AUTOGENERATED")
        assert text.count("/*") == 2, name
    for name in ("player.bundle.js", "common.bundle.js"):
        text = (WWW / "js" / name).read_text("utf-8")
        assert text.startswith("/* AUTOGENERATED")
        # header (2) + one banner per module, nothing else
        modules = (
            build_bundle.PLAYER_MODULES
            if name.startswith("player")
            else build_bundle.COMMON_MODULES
        )
        assert text.count("/*") == 2 + len(modules), name
        assert not re.search(r"^\s*//", text, re.M), name


def test_build_is_deterministic():
    a = build_bundle._concat(build_bundle.COMMON_MODULES)
    assert a == build_bundle._concat(build_bundle.COMMON_MODULES)
    assert build_css.strip_css(build_css.module_text("01-base.css", "styles.css"))
