#!/usr/bin/env python3
"""Comment strippers for the generated CSS / JS bundles (#1224).

``build_css.py`` and ``build_bundle.py`` used to concatenate the source modules
verbatim, so every design-rationale comment shipped to every phone and TV
(a guest's first load was ~203 KB gzip, ~88 KB without comments). The sources
stay as they are; only the generated outputs go through these functions.

No dependency: a small scanner that knows where code ends and a string, a
template literal, a regex literal or a comment begins. It does **not** minify
(no renaming, no whitespace squeezing inside code), so the output is the source
minus its comments, with the lines they leave empty removed. Deterministic, and
idempotent: stripping stripped text changes nothing.

Kept on purpose: ``/*! ... */`` legal comments. The callers prepend their own
AUTOGENERATED header *after* stripping.
"""

from __future__ import annotations

_IDENT = set(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_$"
)
# After one of these words a "/" starts a regex, not a division.
_REGEX_KEYWORDS = {
    "return", "typeof", "instanceof", "in", "of", "new", "delete", "void",
    "throw", "case", "do", "else", "yield", "await",
}


def _is_ident_char(ch: str) -> bool:
    return ch in _IDENT or ord(ch) > 127


def _scan(text: str, *, js: bool) -> list[tuple[str, int, int]]:
    """Split ``text`` into ``(kind, start, end)`` spans.

    kinds: ``code`` (anything else), ``str``, ``tpl`` (template text, the
    ``${`` / ``}`` delimiters are code), ``re``, ``line`` / ``block`` /
    ``legal`` comments.
    """
    spans: list[tuple[str, int, int]] = []
    n = len(text)
    i = 0
    code_start = 0
    # JS: is a "/" at this point a regex start? Decided by the last
    # significant token.
    regex_ok = True
    # Template-literal nesting: each entry is the brace depth at which the
    # enclosing ``${`` was opened.
    tpl_stack: list[int] = []
    depth = 0

    def flush(upto: int) -> None:
        nonlocal code_start
        if upto > code_start:
            spans.append(("code", code_start, upto))
        code_start = upto

    def read_template(pos: int, start: int) -> int:
        """Scan template text from ``pos`` (after ` or }); return index after
        the closing backtick, or after ``${`` (pushing the stack)."""
        nonlocal depth
        j = pos
        while j < n:
            c = text[j]
            if c == "\\":
                j += 2
                continue
            if c == "`":
                spans.append(("tpl", start, j + 1))
                return j + 1
            if c == "$" and j + 1 < n and text[j + 1] == "{":
                spans.append(("tpl", start, j + 2))
                tpl_stack.append(depth)
                depth += 1
                return j + 2
            j += 1
        spans.append(("tpl", start, n))
        return n

    while i < n:
        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if ch == "/" and nxt == "*":
            end = text.find("*/", i + 2)
            end = n if end < 0 else end + 2
            flush(i)
            kind = "legal" if text.startswith("/*!", i) else "block"
            spans.append((kind, i, end))
            code_start = i = end
            continue
        if js and ch == "/" and nxt == "/":
            end = text.find("\n", i)
            end = n if end < 0 else end
            flush(i)
            spans.append(("line", i, end))
            code_start = i = end
            continue
        if ch in "'\"":
            j = i + 1
            while j < n and text[j] != ch:
                if text[j] == "\\":
                    j += 1
                elif text[j] == "\n" and js:
                    break
                j += 1
            flush(i)
            spans.append(("str", i, min(j + 1, n)))
            code_start = i = min(j + 1, n)
            regex_ok = False
            continue
        if not js and ch == "(" and text[max(0, i - 3):i].lower() == "url":
            # Unquoted url(...) may contain "/*" or "//"; quoted is a string.
            j = i + 1
            while j < n and text[j] in " \t\n":
                j += 1
            if j < n and text[j] not in "'\"":
                end = text.find(")", j)
                end = n if end < 0 else end
                flush(i + 1)
                spans.append(("str", i + 1, end))
                code_start = i = end
                continue
        if js and ch == "`":
            flush(i)
            i = read_template(i + 1, i)
            code_start = i
            regex_ok = False
            continue
        if js and ch == "{":
            depth += 1
        elif js and ch == "}":
            depth -= 1
            if tpl_stack and depth == tpl_stack[-1]:
                tpl_stack.pop()
                flush(i)
                # the "}" belongs to the template run that follows
                i = read_template(i + 1, i)
                code_start = i
                regex_ok = False
                continue
        if js and ch == "/":
            if regex_ok:
                j = i + 1
                in_class = False
                while j < n:
                    c = text[j]
                    if c == "\\":
                        j += 2
                        continue
                    if c == "\n":
                        break
                    if c == "[":
                        in_class = True
                    elif c == "]":
                        in_class = False
                    elif c == "/" and not in_class:
                        break
                    j += 1
                j += 1
                while j < n and _is_ident_char(text[j]):
                    j += 1
                flush(i)
                spans.append(("re", i, j))
                code_start = i = j
                regex_ok = False
                continue
            regex_ok = True
            i += 1
            continue
        if js:
            if _is_ident_char(ch):
                j = i
                while j < n and _is_ident_char(text[j]):
                    j += 1
                regex_ok = text[i:j] in _REGEX_KEYWORDS
                i = j
                continue
            if ch in " \t\r\n":
                i += 1
                continue
            # punctuator: a regex may follow, except after ) ] }
            regex_ok = ch not in ")]}"
        i += 1
    flush(n)
    return spans


def _strip(text: str, *, js: bool) -> str:
    out: list[str] = []

    def tail(k: int = 3) -> str:
        """The last ``k`` characters written so far."""
        buf = ""
        for piece in reversed(out):
            buf = piece + buf
            if len(buf) >= k:
                break
        return buf[-k:]

    def rstrip_hspace() -> None:
        while out:
            s = out[-1].rstrip(" \t")
            if s:
                out[-1] = s
                return
            out.pop()

    n = len(text)
    drop_nl = False  # a comment-only line was removed: eat its newline
    trim = 0  # characters of the next code span already consumed
    for kind, a, b in _scan(text, js=js):
        piece = text[a:b]
        if kind in ("line", "block"):
            rstrip_hspace()
            k = b
            while k < n and text[k] in " \t":
                k += 1
            trim = k - b
            nxt = text[k] if k < n else "\n"
            before = tail(1)
            if before in ("", "\n") and nxt == "\n":
                drop_nl = True
                continue
            if kind == "block" and "\n" in piece:
                out.append("\n")
            elif before and before not in " \t\n" and nxt not in " \t\n":
                out.append(" ")
            continue
        if kind == "code":
            piece = piece[trim:]
            if drop_nl and piece.startswith("\n"):
                piece = piece[1:]
                # no second blank line where a comment block used to sit
                if piece.startswith("\n") and tail(2) in ("\n\n", "\n", ""):
                    piece = piece[1:]
        trim = 0
        drop_nl = False
        out.append(piece)
    return "".join(out)


def strip_css(text: str) -> str:
    """Remove ``/* ... */`` blocks (not inside strings or ``url()``)."""
    return _strip(text, js=False)


def strip_js(text: str) -> str:
    """Remove ``//`` and ``/* */`` comments, keeping ``/*! */`` legal ones."""
    return _strip(text, js=True)


def js_tokens(text: str) -> list[str]:
    """Everything of a JS text that is not a comment or whitespace-only code,
    as a list of spans; used to prove stripping removed comments and nothing
    else."""
    import re

    tokens: list[str] = []
    for kind, a, b in _scan(text, js=True):
        piece = text[a:b]
        if kind in ("line", "block"):
            continue
        if kind == "code":
            tokens.extend(re.findall(r"[A-Za-z0-9_$\u0080-￿]+|[^\sA-Za-z0-9_$]", piece))
        else:
            tokens.append(piece)
    return tokens
